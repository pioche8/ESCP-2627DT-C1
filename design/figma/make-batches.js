/*
 * design/figma/make-batches.js — turns the capture.js trees into ready-to-run Figma Plugin API scripts
 * (design/figma/out/figma/NN-*.js) for the Figma MCP use_figma tool, in the order they must run, each under the tool's
 * script limit. Also writes out/figma/RUN.md with the order and what each script does. Dev-only; Playwright is only
 * used to re-encode the photos as small JPEGs. Run capture.js first.
 *
 *   node design/figma/make-batches.js            all scripts
 *   node design/figma/make-batches.js --check    only report: raw colours, dark/light differences, batch sizes
 *
 * Why batches: the Starter plan caps the number of MCP tool calls, so each call should carry as many screens as fit.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const HERE = __dirname;
const ROOT = path.resolve(HERE, '..', '..');
const OUT = process.env.OUT || path.join(HERE, 'out');
const DEST = path.join(OUT, 'figma');
const cfg = JSON.parse(fs.readFileSync(path.join(HERE, 'figma.config.json'), 'utf8'));
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, 'shared', 'tokens.json'), 'utf8'));
const CHECK = process.argv.includes('--check');
const tpl = (f) => fs.readFileSync(path.join(HERE, f), 'utf8').replace(/^\/\/.*\n/gm, '');
const consts = (o) => Object.entries(o).map(([k, v]) => 'const ' + k + ' = ' + JSON.stringify(v) + ';').join('\n') + '\n';
const header = (what) => '// ' + what + ' · generated by design/figma/make-batches.js for Figma file ' + cfg.fileKey + ' · run with use_figma\n';

function load(scheme) {
  const idxFile = path.join(OUT, scheme, 'index.json');
  if (!fs.existsSync(idxFile)) return null;
  return JSON.parse(fs.readFileSync(idxFile, 'utf8')).map((e) => {
    const s = JSON.parse(fs.readFileSync(path.join(OUT, scheme, e.file + '.json'), 'utf8'));
    const compact = (n) => { if (n.k === 'T' && n.ws) delete n.h; (n.ch || []).forEach(compact); };
    s.ch.forEach(compact);
    return { name: s.name, H: s.H, bg: s.bg, ch: s.ch };
  });
}
const round = (s) => JSON.stringify(s, (k, v) => (typeof v === 'number' ? Math.round(v) : v));
const raws = (s) => [...new Set((JSON.stringify(s).match(/"#[0-9A-F]{6}"/g) || []))];
function pack(screens, fixedFor, budget) {
  const batches = []; let cur = [], size = 0;
  for (const s of screens) {
    const j = JSON.stringify(s);
    if (j.length > budget) throw new Error(s.name + ' alone is ' + j.length + ' chars, over the ' + budget + ' budget');
    if (size + j.length + 2 > budget && cur.length) { batches.push(cur); cur = []; size = 0; }
    cur.push(j); size += j.length + 2;
  }
  if (cur.length) batches.push(cur);
  return batches.map((b, i) => fixedFor(i) + 'const S = [\n' + b.join(',\n') + '\n];\n');
}
async function encodePhotos(names) {
  const { chromium } = require('playwright');
  const browser = await chromium.launch(); const page = await browser.newPage();
  const out = {};
  for (const n of names) {
    const src = 'data:image/png;base64,' + fs.readFileSync(path.join(ROOT, 'assets', 'img', n + '.png')).toString('base64');
    const b64 = await page.evaluate(async (s) => { const img = new Image(); img.src = s; await img.decode(); const c = document.createElement('canvas'); c.width = img.naturalWidth; c.height = img.naturalHeight; c.getContext('2d').drawImage(img, 0, 0); return c.toDataURL('image/jpeg', 0.72).split(',')[1]; }, src);
    const bytes = Buffer.from(b64, 'base64'); let sum = 0; for (const x of bytes) sum = (sum + x) >>> 0;
    out[n] = { b64, len: bytes.length, sum };
  }
  await browser.close();
  return out;
}

(async () => {
  const dark = load('dark');
  if (!dark) { console.error('No capture in ' + path.relative(ROOT, OUT) + '/dark: run node design/figma/capture.js first.'); process.exit(2); }
  const light = load('light');
  const names = dark.map((s) => s.name);
  const raw = dark.flatMap((s) => raws(s).map((h) => s.name + ': ' + h));
  const lightByName = new Map((light || []).map((s) => [s.name, s]));
  const differs = light ? dark.filter((s) => !lightByName.has(s.name) || round(lightByName.get(s.name)) !== round(s)).map((s) => s.name) : [];
  console.log(dark.length + ' screens · ' + (raw.length ? raw.length + ' raw colours outside the tokens:\n  ' + raw.join('\n  ') : 'every colour is a token'));
  console.log(light ? 'light capture: ' + (differs.length ? differs.length + ' screen(s) differ from dark beyond the colours, built from the light capture: ' + differs.join(', ') : 'identical structure, the light page is a recoloured copy') : 'no light capture: the light page is a recoloured copy of every dark screen');
  const REPLACE = [...new Set(cfg.legacyFrames.concat(names))];
  const builder = tpl('builder.figma.js');
  // the first dark batch also removes the first-attempt frames; later batches replace only their own frames
  const fixedDark = (i) => consts({ PAGE: cfg.pages.dark, PAGE_NAME: cfg.pageNames.dark, COLL: cfg.collections.dark, SB: cfg.components.statusBar, HI: cfg.components.homeIndicator, REPLACE: i === 0 ? cfg.legacyFrames : [] });
  const budget = cfg.maxScript - builder.length - fixedDark(0).length - 400;
  const scripts = [];
  pack(dark, fixedDark, budget).forEach((b, i, all) => scripts.push(['screens-dark-' + (i + 1), 'Build iPhone screens (dark) batch ' + (i + 1) + ' of ' + all.length + ': ' + (b.match(/"name":"[^"]+"/g) || []).map((m) => m.slice(8, -1)).join(', '), b + builder]));
  scripts.push(['light-copy', 'Copy the dark iPhone frames onto the light page and rebind every colour to the light variables', consts({ DARK_PAGE: cfg.pages.dark, LIGHT_PAGE: cfg.pages.light, LIGHT_PAGE_NAME: cfg.pageNames.light, DARK_COLL: cfg.collections.dark, LIGHT_COLL: cfg.collections.light, NAMES: names.filter((n) => differs.indexOf(n) === -1), REPLACE }) + tpl('light.figma.js')]);
  if (differs.length) {
    const fixedLight = () => consts({ PAGE: cfg.pages.light, PAGE_NAME: cfg.pageNames.light, COLL: cfg.collections.light, SB: cfg.components.statusBar, HI: cfg.components.homeIndicator, REPLACE: [] });
    pack(light.filter((s) => differs.indexOf(s.name) !== -1), fixedLight, budget).forEach((b, i) => scripts.push(['screens-light-' + (i + 1), 'Build the light screens that differ from dark beyond colour (status bar and home indicator rebound to light ink afterwards by light-copy if re-run)', b + builder.replace("return { screens: out", "for (const f of out) { const fr = await figma.getNodeByIdAsync(f.id); for (const inst of fr.findAllWithCriteria({ types: ['INSTANCE'] })) for (const n of inst.findAll(() => true)) { if (n.type !== 'FRAME' && 'fills' in n && Array.isArray(n.fills) && n.fills.length) n.fills = n.fills.map((p) => p.type === 'SOLID' ? figma.variables.setBoundVariableForPaint(p, 'color', V.ink) : p); if (n.type !== 'FRAME' && 'strokes' in n && Array.isArray(n.strokes) && n.strokes.length) n.strokes = n.strokes.map((p) => p.type === 'SOLID' ? figma.variables.setBoundVariableForPaint(p, 'color', V.ink) : p); } }\nreturn { screens: out")]));
  }
  const photoNames = [...new Set(JSON.stringify(dark).match(/"img":"[^"]+"/g).map((m) => m.slice(7, -1)))];
  if (!CHECK) {
    const photos = await encodePhotos(photoNames);
    const photoTpl = tpl('photos.figma.js');
    let group = {}, size = 0, n = 0;
    const flush = () => { if (!Object.keys(group).length) return; scripts.push(['photos-' + (++n), 'Place the photos (' + Object.keys(group).join(', ') + ') on both iPhone pages, checked byte by byte', consts({ PAGES: [cfg.pages.dark, cfg.pages.light], IMAGES: group }) + photoTpl]); group = {}; size = 0; };
    for (const k of photoNames) { const len = photos[k].b64.length + 80; if (size + len > cfg.maxScript - photoTpl.length - 400) flush(); group[k] = photos[k]; size += len; }
    flush();
  }
  scripts.push(['prototype-dark', 'Prototype links on the dark iPhone page (BRIEF.md demo path, tab bar, Back, About)', consts({ PAGE: cfg.pages.dark, FLOW_NAME: cfg.flowName }) + tpl('prototype.figma.js')]);
  scripts.push(['prototype-light', 'Prototype links on the light iPhone page', consts({ PAGE: cfg.pages.light, FLOW_NAME: cfg.flowName.replace('(iPhone)', '(iPhone, light)') }) + tpl('prototype.figma.js')]);
  scripts.push(['design-system', 'Design system section on the first page: colour swatches, App/… text styles, Status / Score tile / Button component sets', consts({ PAGE: cfg.pages.overview, DARK_COLL: cfg.collections.dark, LIGHT_COLL: cfg.collections.light, TYPE: tokens.type.app, SECTION_NAME: cfg.designSystemSection }) + tpl('design-system.figma.js')]);
  scripts.push(['cleanup', 'Remove the superseded first-attempt sections on the first page (exact ids and names only)', consts({ PAGE: cfg.pages.overview, REMOVE: cfg.cleanup }) + tpl('cleanup.figma.js')]);

  // merge scripts that work on the same page into one call (each part runs in its own async scope, in order)
  const merge = (slug, parts) => [slug, parts.map((p) => p[1]).join(' · then ') , 'const R = {};\n' + parts.map((p) => 'R[' + JSON.stringify(p[0]) + '] = await (async () => {\n' + p[2] + '\n})().catch((e) => ({ error: String(e && e.message || e).slice(0, 300) }));').join('\n') + '\nreturn R;\n'];
  const take = (re) => scripts.filter((s) => re.test(s[0]));
  const darkParts = take(/^screens-dark-/), calls = [];
  darkParts.forEach((p, i) => calls.push(i === darkParts.length - 1 ? merge(p[0] + '+prototype', [p].concat(take(/^prototype-dark$/))) : p));
  calls.push(merge('light-page', take(/^light-copy$/).concat(take(/^screens-light-/), take(/^prototype-light$/))));
  take(/^photos-/).forEach((p) => calls.push(p));
  calls.push(merge('overview-page', take(/^design-system$/).concat(take(/^cleanup$/))));
  scripts.length = 0; calls.forEach((c) => scripts.push(c));
  const rows = scripts.map(([slug, what, code], i) => ({ file: String(i + 1).padStart(2, '0') + '-' + slug + '.js', what, size: code.length }));
  const over = rows.filter((r) => r.size > 50000);
  console.log(scripts.length + ' Figma calls:\n' + rows.map((r) => '  ' + r.file + '  ' + (r.size / 1000).toFixed(1) + ' kB  ' + r.what).join('\n'));
  if (over.length) { console.error('over the 50,000-character use_figma limit: ' + over.map((r) => r.file).join(', ')); process.exitCode = 1; }
  if (CHECK) return;
  fs.rmSync(DEST, { recursive: true, force: true });
  fs.mkdirSync(DEST, { recursive: true });
  scripts.forEach(([slug, what, code], i) => fs.writeFileSync(path.join(DEST, rows[i].file), header(what) + code));
  fs.writeFileSync(path.join(DEST, 'RUN.md'), '# Figma build scripts\n\nRun in this order with the Figma MCP `use_figma` tool on file `' + cfg.fileKey + '` (' + cfg.url + '), after `create_session`. Each file is the whole `code` argument. Re-running a script is safe: it replaces only the frames, sections and styles it owns.\n\n| # | Script | Size | What it does |\n|---|---|---|---|\n' + rows.map((r, i) => '| ' + (i + 1) + ' | `' + r.file + '` | ' + (r.size / 1000).toFixed(1) + ' kB | ' + r.what + ' |').join('\n') + '\n\nIf `mcp.figma.com` is reachable, the photos can instead go up with `upload_assets` (nodeIds = the `photo · …` rectangles) and the PNGs in `assets/img/`.\n');
  console.log('wrote ' + path.relative(ROOT, DEST) + '/ (RUN.md lists the order)');
})().catch((e) => { console.error(e); process.exit(1); });
