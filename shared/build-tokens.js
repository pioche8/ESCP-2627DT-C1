#!/usr/bin/env node
/*
 * TenderScout · shared/build-tokens.js
 * Reads shared/tokens.json (the only place colours, type, radii, shadows, easing and durations are written) and emits:
 *   shared/tokens.css                 custom properties for the app (plain stylesheet, no build step, works from file://)
 *   site/src/styles/tokens.css        the same values as a Tailwind v4 @theme block + :root for the website
 *   site/src/generated/tokens.ts      the JSON as a typed TS module (PhoneDemo, Map, VerdictTile read colours from it)
 *   .design-cache/tenderscout.md      token sheet for the design-drift scanner (gitignored, session-local)
 * Run: node shared/build-tokens.js      (also runs from site/: `npm run tokens`)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const T = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
const stamp = 'Generated by shared/build-tokens.js from shared/tokens.json (v' + T.version + '). Do not edit by hand.';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
// Flatten { map: { bg } } → [['map-bg', '#..']], skipping $comment keys and arrays
function flat(obj, prefix) {
  const out = [];
  Object.keys(obj).forEach((k) => {
    if (k.startsWith('$')) return;
    const v = obj[k], name = (prefix ? prefix + '-' : '') + kebab(k);
    if (isObj(v)) out.push(...flat(v, name));
    else if (Array.isArray(v)) v.forEach((x, i) => { if (!isObj(x)) out.push([name + '-' + (i + 1), String(x)]); });
    else out.push([name, String(v)]);
  });
  return out;
}
const ms = (v) => (typeof v === 'number' ? v + 'ms' : String(v));

/* ---------- shared custom properties (site + app read these) ---------- */
function sharedVars() {
  const lines = [];
  lines.push('  /* fonts */');
  lines.push('  --font-ui: ' + T.font.family.ui + ';');
  lines.push('  --font-mono: ' + T.font.family.mono + ';');
  lines.push('  --font-icon: ' + T.font.family.icon + ';');
  lines.push('  /* easing (design/MOTION.md: enter easeOut, morph easeInOutQuart, pop easeOutBack) */');
  Object.keys(T.easing).filter((k) => !k.startsWith('$')).forEach((k) => lines.push('  --ease-' + kebab(k) + ': ' + T.easing[k] + ';'));
  lines.push('  --ease-out: ' + T.easing.enter + '; --ease-back: ' + T.easing.pop + ';'); // the app\'s historical names
  lines.push('  /* durations */');
  flat(T.duration).forEach(([k, v]) => lines.push('  --dur-' + k + ': ' + ms(/^\d+$/.test(v) ? +v : v) + ';'));
  lines.push('  /* site colours (--ts-*) */');
  flat(T.color.site).forEach(([k, v]) => lines.push('  --ts-' + k + ': ' + v + ';'));
  lines.push('  /* verdicts: shape + label + colour, never colour alone */');
  ['go', 'maybe', 'nogo', 'check'].forEach((v) => {
    const d = T.verdict[v];
    lines.push('  --ts-' + v + ': ' + d.solid + '; --ts-' + v + '-on: ' + d.on + '; --ts-' + v + '-text: ' + d.onDark + '; --ts-' + v + '-soft: ' + d.soft + '; --ts-' + v + '-ink: ' + d.ink + ';' + (d.solidSmall ? ' --ts-' + v + '-small: ' + d.solidSmall + ';' : '') + (d.ring ? ' --ts-' + v + '-ring: ' + d.ring + ';' : ''));
  });
  lines.push('  --ts-maybe-clip: ' + T.verdict.maybe.clip + ';');
  lines.push('  /* flags (CSS stripe chips) and the paper quote card */');
  flat(T.flags).forEach(([k, v]) => lines.push('  --flag-' + k + ': ' + v + ';'));
  flat(T.paper).forEach(([k, v]) => lines.push('  --paper-' + k + ': ' + v + ';'));
  lines.push('  /* radii, shadows, glow, grain, image treatment */');
  flat(T.radius.site).forEach(([k, v]) => lines.push('  --r-' + k + ': ' + v + ';'));
  flat(T.radius.app).forEach(([k, v]) => lines.push('  --r-app-' + k + ': ' + v + ';'));
  flat(T.shadow).forEach(([k, v]) => lines.push('  --shadow-' + k + ': ' + v + ';'));
  Object.keys(T.glow).forEach((k) => { if (!k.startsWith('$') && typeof T.glow[k] === 'string') lines.push('  --glow-' + kebab(k) + ': ' + T.glow[k] + ';'); });
  T.glow.orbs.forEach((g, i) => lines.push('  --glow-orb-' + (i + 1) + ': ' + g + ';'));
  lines.push('  --grain: url("' + T.grain.svg + '"); --grain-opacity: ' + T.grain.opacity + '; --grain-opacity-hero: ' + T.grain.opacityHero + ';');
  lines.push('  --img-filter: ' + T.image.filter + '; --img-tint: ' + T.image.tint + '; --img-fallback: ' + T.image.fallbackBg + ';');
  lines.push('  /* layout */');
  flat(T.layout.site).forEach(([k, v]) => lines.push('  --site-' + k + ': ' + v + ';'));
  flat(T.layout.app).forEach(([k, v]) => lines.push('  --app-' + k + ': ' + v + ';'));
  lines.push('  --safe-top: env(safe-area-inset-top, 0px); --safe-bottom: env(safe-area-inset-bottom, 0px);');
  return lines.join('\n');
}

/* ---------- app themes: every --v-* token for every palette × scheme ---------- */
function themeBlock(theme, scheme) {
  const t = T.color.app.themes[theme][scheme];
  const lines = Object.keys(t).filter((k) => k !== 'go-glass').map((k) => '  --v-' + k + ': ' + t[k] + ';');
  lines.push(t['go-glass'] === 'light' ? '  --v-go-glass: var(--v-glass-light); --v-go-glass-ink: var(--v-go-on);' : '  --v-go-glass: var(--v-glass-dark); --v-go-glass-ink: #FFFFFF;');
  lines.push('  color-scheme: ' + scheme + ';');
  return lines.join('\n');
}
function appThemes() {
  const def = T.color.app.default, out = [];
  out.push('/* App palettes: <html data-v3="light|dark" data-palette="' + T.color.app.palettes.join('|') + '">. Default: ' + def + '. */');
  out.push(':root, [data-v3="light"], [data-v3="light"][data-palette="' + def + '"] {\n' + themeBlock(def, 'light') + '\n}');
  out.push('[data-v3="dark"], [data-v3="dark"][data-palette="' + def + '"] {\n' + themeBlock(def, 'dark') + '\n}');
  T.color.app.palettes.filter((p) => p !== def).forEach((p) => {
    out.push('[data-v3="light"][data-palette="' + p + '"] {\n' + themeBlock(p, 'light') + '\n}');
    out.push('[data-v3="dark"][data-palette="' + p + '"] {\n' + themeBlock(p, 'dark') + '\n}');
  });
  return out.join('\n');
}

/* ---------- 1. shared/tokens.css ---------- */
const sharedCss = '/* ' + stamp + '\n * The app loads this file before styles.css; the website imports the same values through site/src/styles/tokens.css. */\n' +
  ':root {\n' + sharedVars() + '\n}\n' + appThemes() + '\n';
fs.writeFileSync(path.join(__dirname, 'tokens.css'), sharedCss);

/* ---------- 2. site/src/styles/tokens.css (Tailwind v4 @theme) ---------- */
function tailwindTheme() {
  const l = [];
  l.push('  --color-*: initial;'); // only TenderScout colours become utilities (bg-ts-bg, text-ts-text2 …)
  flat(T.color.site).forEach(([k, v]) => l.push('  --color-ts-' + k + ': ' + v + ';'));
  ['go', 'maybe', 'nogo', 'check'].forEach((v) => {
    const d = T.verdict[v];
    l.push('  --color-ts-' + v + ': ' + d.solid + '; --color-ts-' + v + '-on: ' + d.on + '; --color-ts-' + v + '-text: ' + d.onDark + '; --color-ts-' + v + '-soft: ' + d.soft + '; --color-ts-' + v + '-ink: ' + d.ink + ';');
  });
  l.push('  --color-white: #FFFFFF; --color-black: #000000; --color-transparent: transparent; --color-current: currentColor;');
  l.push('  --font-ui: ' + T.font.family.ui + ';');
  l.push('  --font-mono: ' + T.font.family.mono + ';');
  l.push('  --font-icon: ' + T.font.family.icon + ';');
  l.push('  --radius-*: initial;');
  flat(T.radius.site).forEach(([k, v]) => l.push('  --radius-' + k + ': ' + v + ';'));
  l.push('  --shadow-*: initial;');
  flat(T.shadow).forEach(([k, v]) => l.push('  --shadow-' + k + ': ' + v + ';'));
  l.push('  --ease-*: initial;');
  Object.keys(T.easing).filter((k) => !k.startsWith('$')).forEach((k) => l.push('  --ease-' + kebab(k) + ': ' + T.easing[k] + ';'));
  Object.keys(T.type.site).forEach((k) => {
    const s = T.type.site[k], n = 'ts-' + kebab(k);
    l.push('  --text-' + n + ': ' + s.size + '; --text-' + n + '--line-height: ' + s.line + '; --text-' + n + '--font-weight: ' + s.weight + '; --text-' + n + '--letter-spacing: ' + s.tracking + ';');
  });
  l.push('  --breakpoint-*: initial; --breakpoint-sm: 390px; --breakpoint-md: 768px; --breakpoint-lg: 1024px; --breakpoint-xl: 1440px;');
  l.push('  --container-site: ' + T.layout.site.maxWidth + '; --container-site-wide: ' + T.layout.site.maxWidthWide + ';');
  return l.join('\n');
}
const siteCss = '/* ' + stamp + ' */\n@theme {\n' + tailwindTheme() + '\n}\n:root {\n' + sharedVars() + '\n}\n';
const siteStyles = path.join(ROOT, 'site', 'src', 'styles');
if (fs.existsSync(path.join(ROOT, 'site'))) {
  fs.mkdirSync(siteStyles, { recursive: true });
  fs.writeFileSync(path.join(siteStyles, 'tokens.css'), siteCss);
  const gen = path.join(ROOT, 'site', 'src', 'generated');
  fs.mkdirSync(gen, { recursive: true });
  const clean = JSON.parse(JSON.stringify(T, (k, v) => (k.startsWith('$') ? undefined : v)));
  fs.writeFileSync(path.join(gen, 'tokens.ts'), '// ' + stamp + '\nexport const tokens = ' + JSON.stringify(clean, null, 2) + ' as const;\nexport type Tokens = typeof tokens;\nexport default tokens;\n');
}

/* ---------- 3. design-drift cache (tokens the scanner can parse) ---------- */
const hexes = new Set();
JSON.stringify(T).replace(/#[0-9A-Fa-f]{6}\b/g, (h) => { hexes.add(h.toUpperCase()); return h; });
const md = ['# TenderScout design system (generated from shared/tokens.json v' + T.version + ')', '',
  'Font family: `Hanken Grotesk` for all UI and headings; font-family: `IBM Plex Mono` for labels, codes, citations and counters; icons `Material Symbols Rounded`.', '',
  '## Colours', '', [...hexes].sort().map((h) => '- `' + h + '`').join('\n'), '',
  '## Border radius', '', 'border-radius: ' + [...new Set(flat(T.radius).map(([, v]) => v))].join(', '), '',
  '## Rules', '', '- MUST show every verdict as shape + label + colour (Go ● / Maybe ▲ / No-go ■ / Needs your check ◆).',
  '- MUST keep "Simulated AI" and "fictional" labels visible wherever AI output or demo data appears.',
  '- NEVER use a colour that is not in shared/tokens.json; add it there and rebuild.',
  '- NEVER put text on the grain or glow where contrast would drop below WCAG AA 4.5:1.',
  '- NEVER use typewriter reveals on headlines, gradients on text (except the hero wordmark), stock people, testimonials, or numbers that are not in data.js.'].join('\n') + '\n';
fs.mkdirSync(path.join(ROOT, '.design-cache'), { recursive: true });
fs.writeFileSync(path.join(ROOT, '.design-cache', 'tenderscout.md'), md);

console.log('tokens: shared/tokens.css (' + sharedCss.length + ' B)' + (fs.existsSync(path.join(ROOT, 'site')) ? ', site/src/styles/tokens.css, site/src/generated/tokens.ts' : '') + ', .design-cache/tenderscout.md · ' + hexes.size + ' colours');
