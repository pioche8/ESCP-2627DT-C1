#!/usr/bin/env node
/*
 * TenderScout · shared/build-tokens.js
 * Reads shared/tokens.json (the only place colours, type, radius, easing and durations are written) and emits:
 *   shared/tokens.css                 custom properties for the app (plain stylesheet, no build step, works from file://)
 *   (not the website: since 5 Nov 2026 site/src/styles/tokens.css and site/src/generated/tokens.ts are the frozen 3 Nov
 *    originals, restored with the original website design; they are edited by hand, CLAUDE.md §11 item 103)
 *   .design-cache/tenderscout.md      token sheet for the design-drift scanner (gitignored, session-local)
 * Run: node shared/build-tokens.js      (also runs from site/: `npm run tokens`)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const T = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
const stamp = 'Generated by shared/build-tokens.js from shared/tokens.json (v' + T.version + '). Do not edit by hand.';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
// Flatten { rescore: { countUp } } → [['rescore-count-up', '650']], skipping $comment keys
function flat(obj, prefix) {
  const out = [];
  Object.keys(obj).forEach((k) => {
    if (k.startsWith('$')) return;
    const v = obj[k], name = (prefix ? prefix + '-' : '') + kebab(k);
    if (isObj(v)) out.push(...flat(v, name));
    else if (Array.isArray(v)) v.forEach((x, i) => { if (!isObj(x)) out.push([name + '-' + (i + 1), String(x)]); });
    else out.push([name, String(v)]);
  });
  return out;
}
const ms = (v) => (typeof v === 'number' ? v + 'ms' : String(v));
const COLORS = ['bg', 'surface', 'ink', 'muted', 'brand', 'go', 'maybe', 'nogo', 'check'];

/* ---------- shared custom properties (site + app read these) ---------- */
function sharedVars() {
  const lines = [];
  lines.push('  /* fonts: one typeface, tabular figures, no negative tracking */');
  lines.push('  --font-ui: ' + T.font.family.ui + ';');
  lines.push('  --font-icon: ' + T.font.family.icon + ';');
  lines.push('  /* easing (design/MOTION.md: enter easeOut, morph easeInOutQuart, pop easeOutBack) */');
  Object.keys(T.easing).filter((k) => !k.startsWith('$')).forEach((k) => lines.push('  --ease-' + kebab(k) + ': ' + T.easing[k] + ';'));
  lines.push('  --ease-out: ' + T.easing.enter + '; --ease-back: ' + T.easing.pop + ';'); // the app's historical names
  lines.push('  /* durations */');
  flat(T.duration).forEach(([k, v]) => lines.push('  --dur-' + k + ': ' + ms(/^\d+$/.test(v) ? +v : v) + ';'));
  lines.push('  /* verdict shapes: ● Go · ▲ Maybe · ■ No-go · ◆ Needs your check */');
  lines.push('  --shape-maybe-clip: ' + T.verdict.maybe.clip + ';');
  lines.push('  /* the one radius, the focus ring */');
  lines.push('  --r: ' + T.radius.base + '; --focus-w: ' + T.focus.width + '; --focus-o: ' + T.focus.offset + ';');
  lines.push('  /* layout */');
  flat(T.layout.site).forEach(([k, v]) => lines.push('  --site-' + k + ': ' + v + ';'));
  flat(T.layout.app).forEach(([k, v]) => lines.push('  --app-' + k + ': ' + v + ';'));
  lines.push('  --safe-top: env(safe-area-inset-top, 0px); --safe-bottom: env(safe-area-inset-bottom, 0px);');
  return lines.join('\n');
}
function schemeVars(scheme) {
  const t = T.color.themes[scheme];
  return COLORS.map((k) => '  --c-' + k + ': ' + t[k] + ';').join('\n') + '\n  color-scheme: ' + scheme + ';';
}

/* ---------- 1. shared/tokens.css (the app) ---------- */
const def = T.color.default, other = T.color.schemes.filter((s) => s !== def)[0];
const sharedCss = '/* ' + stamp + '\n * The app loads this file before styles.css. The website keeps its own tokens (site/src/styles/tokens.css).\n' +
  ' * Schemes: <html data-scheme="light|dark">. Default: ' + def + '. */\n' +
  ':root {\n' + sharedVars() + '\n}\n' +
  ':root, [data-scheme="' + def + '"] {\n' + schemeVars(def) + '\n}\n' +
  '[data-scheme="' + other + '"] {\n' + schemeVars(other) + '\n}\n';
fs.writeFileSync(path.join(__dirname, 'tokens.css'), sharedCss);

/* ---------- 3. design-drift cache (tokens the scanner can parse) ---------- */
const hexes = new Set();
JSON.stringify(T.color).replace(/#[0-9A-Fa-f]{6}\b/g, (h) => { hexes.add(h.toUpperCase()); return h; });
const md = ['# TenderScout design system (generated from shared/tokens.json v' + T.version + ')', '',
  'Font family: `Hanken Grotesk` for everything (tabular figures for numbers); icons `Material Symbols Rounded`. No monospace, no italics, no uppercase, letter-spacing 0.', '',
  '## Colours', '', [...hexes].sort().map((h) => '- `' + h + '`').join('\n'), '',
  '## Border radius', '', 'border-radius: ' + T.radius.base + ' (switches and the 8 px verdict circle are round)', '',
  '## Rules', '', '- MUST show every verdict as shape + label + colour (Go ● / Maybe ▲ / No-go ■ / Needs your check ◆).',
  '- MUST keep "Simulated AI" and "fictional" labels visible wherever AI output or demo data appears.',
  '- NEVER use a colour that is not in shared/tokens.json; add it there and rebuild.',
  '- NEVER use gradients, alpha colours, shadows, grain, pills, borders on cards or inputs, eyebrows, section numbers or file names in visible text.'].join('\n') + '\n';
fs.mkdirSync(path.join(ROOT, '.design-cache'), { recursive: true });
fs.writeFileSync(path.join(ROOT, '.design-cache', 'tenderscout.md'), md);

console.log('tokens: shared/tokens.css (' + sharedCss.length + ' B)' + ', .design-cache/tenderscout.md · ' + hexes.size + ' colours');
